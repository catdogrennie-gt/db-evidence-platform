SELECT /*+ MAX_EXECUTION_TIME(1500) */ TRX_ID, TRX_STATE,
 TRX_MYSQL_THREAD_ID, TRX_ROWS_LOCKED, TRX_ROWS_MODIFIED,
 TIMESTAMPDIFF(SECOND, TRX_STARTED, NOW()) AS transaction_age_seconds,
 COALESCE(TIMESTAMPDIFF(SECOND, TRX_WAIT_STARTED, NOW()),0) AS wait_age_seconds
FROM information_schema.INNODB_TRX ORDER BY TRX_STARTED LIMIT 51
