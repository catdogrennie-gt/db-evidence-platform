SELECT /*+ MAX_EXECUTION_TIME(1500) */ DIGEST,SCHEMA_NAME,
 LEFT(DIGEST_TEXT,500) AS DIGEST_TEXT,COUNT_STAR,SUM_TIMER_WAIT,
 MAX_TIMER_WAIT,SUM_LOCK_TIME,SUM_ROWS_EXAMINED,SUM_ROWS_SENT,
 SUM_CREATED_TMP_TABLES,SUM_CREATED_TMP_DISK_TABLES,
 SUM_NO_INDEX_USED,SUM_ERRORS,SUM_WARNINGS,FIRST_SEEN,LAST_SEEN
FROM performance_schema.events_statements_summary_by_digest
WHERE SCHEMA_NAME NOT IN ('mysql','sys','performance_schema','information_schema')
 AND DIGEST IS NOT NULL ORDER BY SUM_TIMER_WAIT DESC LIMIT 21
